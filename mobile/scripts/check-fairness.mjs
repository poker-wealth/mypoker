#!/usr/bin/env node
/**
 * Pins `src/fairness.ts` — the native port of `frontend/src/lib/fairness.ts`
 * that backs `FairnessScreen.tsx` — to a KNOWN-GOOD vector.
 *
 * The vector is not invented here. It is
 * `frontend/src/lib/__fixtures__/round-vector.json`, produced by
 * `game-server/scripts/gen-fairness-vector.ts` calling the real, shipped
 * server functions in `game-server/src/fairness/` — the same fixture the web
 * module's own tests (`frontend/src/lib/fairness.test.ts`) pin against, and
 * which the server's own `verifyRound` accepts before that script even
 * writes it out. So passing this check does not mean "this file agrees with
 * itself" — it means this file's hash construction reproduces what the
 * production server actually computed for a real round.
 *
 * That is the only thing worth checking. `sha256Hex`/`sha256Raw` in
 * `fairness.ts` are almost entirely string/byte-layout code — separators,
 * concatenation order, hex vs raw-byte hashing, big-endian reads — wrapped
 * around a single primitive (`expo-crypto`'s `digest`). The primitive itself
 * is native code with its own test suite; it is not what a port like this
 * gets wrong. The layout is. So `expo-crypto` is stubbed with Node's
 * `crypto.createHash('sha256')` — legitimate here specifically because nothing
 * this script exists to catch depends on which SHA-256 implementation runs
 * underneath.
 *
 * Run: npm run check:fairness
 */

import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const here = path.dirname(fileURLToPath(import.meta.url));
const mobileRoot = path.join(here, '..');
const repoRoot = path.join(mobileRoot, '..');
const require_ = createRequire(path.join(mobileRoot, '/'));
const ts = require_('typescript');

const source = readFileSync(path.join(mobileRoot, 'src', 'fairness.ts'), 'utf8');
const js = ts.transpileModule(source, {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
}).outputText;

// ─── the stub: expo-crypto's digest(), backed by node:crypto ────────────────
//
// `expo-crypto`'s `CryptoDigestAlgorithm.SHA256` is the string `"SHA-256"`
// (not `"sha256"`), so it has to be mapped rather than passed straight to
// `createHash`.
const ALGORITHM_TO_NODE = {
  'SHA-1': 'sha1',
  'SHA-256': 'sha256',
  'SHA-384': 'sha384',
  'SHA-512': 'sha512',
};

function stubDigest(algorithm, data) {
  return new Promise((resolve, reject) => {
    try {
      const nodeAlgorithm = ALGORITHM_TO_NODE[algorithm];
      if (!nodeAlgorithm) throw new Error(`unmapped digest algorithm: ${algorithm}`);
      const bytes = Buffer.from(data.buffer, data.byteOffset, data.byteLength);
      const out = createHash(nodeAlgorithm).update(bytes).digest();
      resolve(out.buffer.slice(out.byteOffset, out.byteOffset + out.byteLength));
    } catch (err) {
      reject(err);
    }
  });
}

const expoCryptoStub = {
  digest: stubDigest,
  CryptoDigestAlgorithm: {
    SHA1: 'SHA-1',
    SHA256: 'SHA-256',
    SHA384: 'SHA-384',
    SHA512: 'SHA-512',
    MD2: 'MD2',
    MD4: 'MD4',
    MD5: 'MD5',
  },
};

function load() {
  const fakeRequire = (id) => {
    if (id === 'expo-crypto') return expoCryptoStub;
    throw new Error('unexpected import: ' + id);
  };
  const module = { exports: {} };
  new Function('require', 'module', 'exports', js)(fakeRequire, module, module.exports);
  return module.exports;
}

const {
  serverCommitOf,
  mergeClientSeeds,
  ownSeedAtSeat,
  computeFinalSeed,
  computeRoundHash,
  standardDeck,
  shuffledDeck,
  verifyMerkleProof,
  verifyRound,
} = load();

// ─── the known-good vector ───────────────────────────────────────────────────
//
// Real production output, not a hand-typed one: this file is generated by
// `game-server/scripts/gen-fairness-vector.ts` from `generateServerCommitment`,
// `mergeClientSeeds`, `computeFinalSeed`, `shuffledDeck`, `computeRoundHash` and
// `MerkleTree` in `game-server/src/fairness/` — the actual server code, not a
// copy of it — and that script refuses to emit it unless the server's OWN
// `verifyRound` accepts it first. `frontend/src/lib/fairness.test.ts` pins the
// web port against this same file for the same reason. A vector this script
// invented would only prove this port agrees with itself; this one proves it
// agrees with the server.
const vectorPath = path.join(repoRoot, 'frontend', 'src', 'lib', '__fixtures__', 'round-vector.json');
const vector = JSON.parse(readFileSync(vectorPath, 'utf8'));

let failures = 0;
async function check(label, run) {
  try {
    await run();
    console.log(`  ok    ${label}`);
  } catch (e) {
    failures++;
    console.log(`  FAIL  ${label}\n          ${e.message.split('\n')[0]}`);
  }
}

console.log('Fairness verifier — native port vs. server-generated vector\n');
console.log(`  vector: ${path.relative(repoRoot, vectorPath)}\n`);

await check('serverCommitOf reproduces the server commitment', async () => {
  const got = await serverCommitOf(vector.serverSeed);
  assert.equal(got, vector.serverCommit);
});

await check('mergeClientSeeds reproduces all_client_seeds', async () => {
  const got = await mergeClientSeeds(vector.seatedClientSeeds);
  assert.equal(got, vector.allClientSeeds);
});

await check('mergeClientSeeds is order-independent input, seat-order output', async () => {
  // Feeding it out of seat order must not change the result — the function
  // itself sorts by seatOrder before hashing.
  const shuffled = [...vector.seatedClientSeeds].reverse();
  const got = await mergeClientSeeds(shuffled);
  assert.equal(got, vector.allClientSeeds);
});

await check('computeFinalSeed reproduces final_seed', async () => {
  const got = await computeFinalSeed(
    vector.serverSeed,
    vector.allClientSeeds,
    vector.futureBlockHash,
    vector.roundId,
  );
  assert.equal(got, vector.finalSeed);
});

await check('computeRoundHash reproduces round_hash', async () => {
  const got = await computeRoundHash(vector);
  assert.equal(got, vector.roundHash);
});

await check('shuffledDeck reproduces the exact dealt order', async () => {
  const got = await shuffledDeck(vector.finalSeed);
  assert.deepEqual(got, vector.cards);
});

await check('shuffledDeck permutes a canonical 52-card deck', async () => {
  const deck = standardDeck();
  assert.equal(deck.length, 52);
  assert.equal(new Set(deck).size, 52);
  const got = await shuffledDeck(vector.finalSeed);
  assert.deepEqual([...got].sort(), [...deck].sort());
});

await check('verifyMerkleProof rebuilds the published root', async () => {
  const got = await verifyMerkleProof(vector.roundHash, vector.merkleProof);
  assert.equal(got, vector.merkleRoot);
});

await check('ownSeedAtSeat finds a seed at its real seat', () => {
  const seat1 = vector.seatedClientSeeds[0];
  assert.equal(ownSeedAtSeat(vector.seatedClientSeeds, seat1), true);
});

await check('ownSeedAtSeat rejects the right seed at the wrong seat', () => {
  const seat1 = vector.seatedClientSeeds[0];
  const seat2 = vector.seatedClientSeeds[1];
  assert.equal(
    ownSeedAtSeat(vector.seatedClientSeeds, { seatOrder: seat2.seatOrder, clientSeed: seat1.clientSeed }),
    false,
  );
});

await check('verifyRound passes all six steps on the untouched vector', async () => {
  const result = await verifyRound(vector);
  const failed = result.steps.filter((s) => !s.pass).map((s) => s.step);
  assert.deepEqual(failed, []);
  assert.equal(result.allPass, true);
});

await check("verifyRound passes step 3 unqualified when the viewer's own seed is present", async () => {
  const mine = vector.seatedClientSeeds[0];
  const result = await verifyRound({ ...vector, mine });
  const step3 = result.steps.find((s) => s.step === 3);
  assert.equal(step3.pass, true);
  assert.equal(step3.note, undefined);
});

await check('verifyRound notes step 3 as unchecked when the viewer did not play', async () => {
  const result = await verifyRound(vector);
  const step3 = result.steps.find((s) => s.step === 3);
  assert.equal(step3.pass, true);
  assert.equal(step3.note, 'OWN_SEED_NOT_CHECKED');
});

await check('verifyRound catches a rewritten round hash — steps 5 and 6 only', async () => {
  const result = await verifyRound({ ...vector, roundHash: 'd'.repeat(64) });
  const failed = result.steps.filter((s) => !s.pass).map((s) => s.step);
  assert.deepEqual(failed, [5, 6]);
});

await check('verifyRound catches a swapped server seed — steps 1 and 2 only', async () => {
  const result = await verifyRound({ ...vector, serverSeed: 'f'.repeat(64) });
  const failed = result.steps.filter((s) => !s.pass).map((s) => s.step);
  assert.deepEqual(failed, [1, 2]);
});

await check('a malformed Merkle proof hex throws rather than reporting tampering', async () => {
  await assert.rejects(
    verifyRound({ ...vector, merkleProof: [{ hash: 'not-hex!!', right: true }] }),
    /hex/i,
  );
});

if (failures > 0) {
  console.log(`\n${failures} check(s) failed.`);
  console.log('A failure here means src/fairness.ts computes a DIFFERENT hash than');
  console.log('the production server for the same inputs — the port has drifted, and');
  console.log('FairnessScreen.tsx would tell a player their honest hand was rigged.');
  process.exit(1);
}

console.log('\nAll checks passed.');
console.log('NOTE: expo-crypto is stubbed with node:crypto here, so this proves the');
console.log("string/byte construction, not expo-crypto's own SHA-256 — that still");
console.log('wants a smoke test on a real device.');
